CREATE TABLE SUMMARY_QUEUE (
 ID                 INTEGER UNSIGNED NOT NULL DEFAULT 0,
 PIREP_ID           INTEGER UNSIGNED NOT NULL DEFAULT 0,
 AIRLINE            CHAR(3) NOT NULL
 CREATED            DATETIME NOT NULL,
 PRIMARY KEY (ID),
 FOREIGN KEY (ID) REFERENCES FLIGHTS(ID) ON UPDATE CASCADE ON DELETE CASCADE,
 FOREIGN KEY (AIRLINE) REFERENCES common.AIRLINES(CODE) ON UPDATE CASCADE ON DELETE CASCADE
) CHARACTER SET latin1;